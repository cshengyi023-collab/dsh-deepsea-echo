/**
 * Build lib/client.js from src/client.template.js, inlining the packaged
 * artwork as data URIs. No bundler, no dependencies — the client bundle is
 * already in the host's lazy-CJS loader form.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const template = readFileSync(join(root, "src", "client.template.js"), "utf8");

const toDataUri = (relative, mime) =>
  `data:${mime};base64,${readFileSync(join(root, relative)).toString("base64")}`;

const fill = (source, key, value) => {
  const token = `__ASSET_${key}__`;
  if (!source.includes(token)) throw new Error(`template is missing ${token}`);
  return source.replace(token, JSON.stringify(value));
};

let out = template;
out = fill(out, "CHIBI", toDataUri("assets/whale-chibi.webp", "image/webp"));
out = fill(out, "SPLASH", toDataUri("assets/whale-splash.webp", "image/webp"));
out = fill(out, "GRAIN", toDataUri("assets/grain.png", "image/png"));
out = fill(out, "SFX_DEEPSEA", toDataUri("assets/sfx/deepsea.wav", "audio/wav"));
out = fill(out, "SFX_ORCHESTRAL", toDataUri("assets/sfx/orchestral.wav", "audio/wav"));
out = fill(out, "SFX_NEON", toDataUri("assets/sfx/neon.wav", "audio/wav"));
out = fill(out, "SFX_CALM", toDataUri("assets/sfx/calm.wav", "audio/wav"));

const banner =
  "/* dsh-whale-startup — generated by scripts/build.mjs; edit src/client.template.js instead. */\n";
out = banner + out;

mkdirSync(join(root, "lib"), { recursive: true });
writeFileSync(join(root, "lib", "client.js"), out, "utf8");
console.log(`lib/client.js written (${(Buffer.byteLength(out) / 1024).toFixed(0)} KiB)`);
